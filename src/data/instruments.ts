export const instrumentAffinity = (instrument: Instrument, targetId: string, kind: string): number => {
  const override = instrument.affinityByTarget?.[targetId];
  if (typeof override === 'number') return override;
  return instrument.affinity[kind as keyof typeof instrument.affinity] ?? 1;
};
